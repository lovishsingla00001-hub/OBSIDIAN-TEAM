import { scanForPII } from './piiScan.js';

/**
 * Integrates PII scan results into the existing SiteCheck report JSON.
 * Attaches the confirmed 'pii' top-level field while preserving all existing
 * security-rule results, scores, summary counts, and report properties.
 *
 * @param {object} report - The base report generated by engine.js.
 * @param {string} html - The already-fetched HTML string from fetchSiteContext().
 * @returns {object} The report enriched with the top-level 'pii' array.
 * @throws {TypeError} If report is not an object or html is not a string.
 */
export function attachPIIToReport(report, html) {
  if (!report || typeof report !== 'object' || Array.isArray(report)) {
    throw new TypeError('Invalid report: report must be a non-null object');
  }

  // scanForPII safely validates that html is a string, throwing TypeError if invalid
  const piiResults = scanForPII(html);

  return {
    ...report,
    pii: piiResults
  };
}

export default attachPIIToReport;
