/**
 * SiteCheck - Integration Test Suite for Step 2
 * Team: Obsidian
 * 
 * Verifies that the PII scanner output integrates into SiteCheck's existing final report:
 * 1. Confirmed field name 'pii' attached at the top level.
 * 2. Phone, email, and Aadhaar-like counts properly reach the report.
 * 3. All existing report fields (url, timestamp, score, summary, results) are preserved without modification.
 * 4. Zero detections result in an empty array `[]`.
 * 5. Input validation and error handling for invalid reports and HTML.
 * 6. Immutability: Base report object is not mutated in-place.
 */

import { attachPIIToReport } from './src/core/integrateReport.js';

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  PASS: ${message}`);
    passed++;
  } else {
    console.error(`  FAIL: ${message}`);
    failed++;
  }
}

function assertDeepEqual(actual, expected, message) {
  const actualStr = JSON.stringify(actual);
  const expectedStr = JSON.stringify(expected);
  if (actualStr === expectedStr) {
    console.log(`  PASS: ${message}`);
    passed++;
  } else {
    console.error(`  FAIL: ${message}\n    Expected: ${expectedStr}\n    Actual:   ${actualStr}`);
    failed++;
  }
}

function assertThrows(fn, expectedErrorType, message) {
  try {
    fn();
    console.error(`  FAIL: ${message} (did not throw)`);
    failed++;
  } catch (err) {
    if (err instanceof expectedErrorType) {
      console.log(`  PASS: ${message}`);
      passed++;
    } else {
      console.error(`  FAIL: ${message} (threw unexpected error: ${err.message})`);
      failed++;
    }
  }
}

console.log('=== SiteCheck Report Integration Test Suite (Step 2) ===\n');

// Mock existing SiteCheck base report generated by engine.js
const mockBaseReport = {
  url: 'https://example-hospital.org',
  timestamp: '2026-10-30T12:00:00.000Z',
  score: 88,
  summary: {
    passed: 7,
    failed: 1,
    warnings: 1
  },
  results: [
    {
      id: 'csp-header',
      name: 'Content Security Policy',
      status: 'passed',
      score: 100
    },
    {
      id: 'hsts-header',
      name: 'HSTS Header',
      status: 'failed',
      score: 0
    }
  ],
  metadata: {
    scanDurationMs: 245,
    engineVersion: '1.2.0'
  }
};

// 1. Integration with fictional HTML containing all 3 PII categories
const fictionalHtmlWithPII = `
  <!DOCTYPE html>
  <html>
    <head><title>Fictional Contact Portal</title></head>
    <body>
      <main>
        <h1>Patient Intake</h1>
        <p>Support: demo@example.com</p>
        <p>Helpline: 9876543210</p>
        <p>Reference ID: 2345 6789 0123</p>
      </main>
    </body>
  </html>
`;

const integratedReport = attachPIIToReport(mockBaseReport, fictionalHtmlWithPII);

console.log('Sample Integrated Report Output:');
console.log(JSON.stringify(integratedReport, null, 2));

// Test 1: PII field is present at top-level
assert(Array.isArray(integratedReport.pii), "Top-level 'pii' property is an Array");

// Test 2: PII field contains expected categories and counts
assertDeepEqual(
  integratedReport.pii,
  [
    { type: 'phone', count: 1 },
    { type: 'email', count: 1 },
    { type: 'aadhaar-like', count: 1 }
  ],
  "Report 'pii' property matches expected detection counts for phone, email, and aadhaar-like"
);

// Test 3: Existing report fields are completely preserved
assert(integratedReport.url === mockBaseReport.url, 'Preserves report.url');
assert(integratedReport.timestamp === mockBaseReport.timestamp, 'Preserves report.timestamp');
assert(integratedReport.score === mockBaseReport.score, 'Preserves report.score');
assertDeepEqual(integratedReport.summary, mockBaseReport.summary, 'Preserves report.summary counts and structure');
assertDeepEqual(integratedReport.results, mockBaseReport.results, 'Preserves report.results array and security rule items');
assertDeepEqual(integratedReport.metadata, mockBaseReport.metadata, 'Preserves report.metadata');

// Test 4: Immutability check - original report was not mutated
assert(mockBaseReport.pii === undefined, 'Original base report was not mutated in-place');

// Test 5: Integration with HTML containing zero PII detections
const cleanHtml = '<html><body><h1>Welcome</h1><p>Clean public documentation page.</p></body></html>';
const cleanReport = attachPIIToReport(mockBaseReport, cleanHtml);
assertDeepEqual(cleanReport.pii, [], "Clean HTML results in empty 'pii' array `[]`");
assert(cleanReport.score === mockBaseReport.score, 'Preserves score on clean HTML report');

// Test 6: Integration with empty HTML string
const emptyReport = attachPIIToReport(mockBaseReport, '');
assertDeepEqual(emptyReport.pii, [], "Empty HTML string results in empty 'pii' array `[]`");

// Test 7: Integration with multiple email addresses and phone formatting
const multiPiiHtml = `
  <div>
    <p>Contact 1: user1@example.com</p>
    <p>Contact 2: user2@sub.example.com</p>
    <p>Hotline: +91 98765-43210</p>
  </div>
`;
const multiReport = attachPIIToReport(mockBaseReport, multiPiiHtml);
assertDeepEqual(
  multiReport.pii,
  [
    { type: 'phone', count: 1 },
    { type: 'email', count: 2 }
  ],
  "Correctly handles multiple emails and formatted phone number without false positives"
);

// Test 8: Error handling for invalid report input
assertThrows(
  () => attachPIIToReport(null, fictionalHtmlWithPII),
  TypeError,
  'Throws TypeError when report is null'
);

assertThrows(
  () => attachPIIToReport(undefined, fictionalHtmlWithPII),
  TypeError,
  'Throws TypeError when report is undefined'
);

assertThrows(
  () => attachPIIToReport('not an object', fictionalHtmlWithPII),
  TypeError,
  'Throws TypeError when report is a string'
);

assertThrows(
  () => attachPIIToReport([1, 2, 3], fictionalHtmlWithPII),
  TypeError,
  'Throws TypeError when report is an Array'
);

// Test 9: Error handling for invalid HTML input
assertThrows(
  () => attachPIIToReport(mockBaseReport, null),
  TypeError,
  'Throws TypeError when HTML is null'
);

assertThrows(
  () => attachPIIToReport(mockBaseReport, 12345),
  TypeError,
  'Throws TypeError when HTML is a number'
);

console.log('\n========================================');
console.log(`Test Summary: ${passed} passed, ${failed} failed`);
console.log('========================================\n');

if (failed > 0) {
  process.exit(1);
}
